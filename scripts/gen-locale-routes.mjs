/**
 * Generates the prefixed-locale route tree.
 *
 * Canonical pages live in apps/web/src/app/(en). For every page.tsx there, this writes a
 * one-line wrapper at the same path under app/[locale] that re-exports the page, so `/hi/...`
 * renders the same component with `params.locale = 'hi'`. Stale wrappers are removed.
 * The hand-written app/[locale]/layout.tsx is left alone.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = join(dirname(fileURLToPath(import.meta.url)), '..', 'apps', 'web', 'src', 'app');
const SRC = join(APP, '(en)');
const DEST = join(APP, '[locale]');
const HEADER = '// Generated by scripts/gen-locale-routes.mjs from app/(en). Do not edit.\n';
/** Folders under (en) that must not get a locale copy. */
const SKIP = new Set(['og']);

// English-only: no prefixed locales, so there is no tree to generate.
const configSource = readFileSync(join(APP, '..', 'i18n', 'config.ts'), 'utf8');
const localeCount = (/export const locales = \[([^\]]*)\]/.exec(configSource)?.[1] ?? '').split(',').filter((x) => x.trim()).length;
if (localeCount < 2) {
  if (existsSync(DEST)) rmSync(DEST, { recursive: true });
  console.log('[routes] one language: no localized pages');
  process.exit(0);
}

function walk(dir, found = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      if (dir === SRC && SKIP.has(name)) continue;
      walk(full, found);
    } else if (name === 'page.tsx' || (name === 'layout.tsx' && dir !== SRC)) {
      // Nested layouts are copied too; the root (en)/layout.tsx has its own [locale] twin.
      found.push(full);
    }
  }
  return found;
}

const exportsName = (source, name) =>
  new RegExp(`export\\s+(async\\s+)?function\\s+${name}\\b|export\\s+const\\s+${name}\\b|export\\s*\\{[^}]*\\b${name}\\b[^}]*\\}`).test(source);

const wanted = new Set();
let written = 0;
for (const page of walk(SRC)) {
  const rel = relative(SRC, page);
  const target = join(DEST, rel);
  wanted.add(target);
  const source = readFileSync(page, 'utf8');
  const names = ['default'];
  for (const name of ['generateMetadata', 'generateStaticParams', 'metadata', 'dynamic']) {
    if (exportsName(source, name)) names.push(name);
  }
  const spec = `@/app/(en)/${rel.split(sep).join('/').replace(/\.tsx$/, '')}`;
  const content = `${HEADER}export { ${names.join(', ')} } from '${spec}';\n`;
  if (!existsSync(target) || readFileSync(target, 'utf8') !== content) {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
    written++;
  }
}

// Remove wrappers whose canonical page is gone, then any directories left empty.
let removed = 0;
function prune(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      prune(full);
      if (readdirSync(full).length === 0) rmSync(full, { recursive: true });
    } else if ((name === 'page.tsx' || name === 'layout.tsx') && !wanted.has(full) && readFileSync(full, 'utf8').startsWith(HEADER)) {
      rmSync(full);
      removed++;
    }
  }
}
if (existsSync(DEST)) prune(DEST);

console.log(`[routes] ${wanted.size} localized pages (${written} written, ${removed} removed)`);
